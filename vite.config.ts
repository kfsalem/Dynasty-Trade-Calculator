/// <reference types="vitest/config" />
import { defineConfig } from 'vitest/config'
import react from '@vitejs/plugin-react'
import tailwindcss from '@tailwindcss/vite'
import type { Plugin } from 'vite'
import { VitePWA } from 'vite-plugin-pwa'

/**
 * The first load's budget, in kB as Vite reports them (#170).
 *
 * 474.7 kB when the tabs were split out on 2026-10-19, down from 552.4. The
 * line sits at Vite's own 500 kB warning, which every build printed for months
 * without anyone acting on it. So this one fails the build instead: going past
 * it means something heavy joined the first load, and it should be lazy.
 */
const FIRST_LOAD_BUDGET_KB = 500

function firstLoadBudget(): Plugin {
  return {
    name: 'first-load-budget',
    apply: 'build',
    generateBundle(_, bundle) {
      for (const chunk of Object.values(bundle)) {
        if (chunk.type !== 'chunk' || !chunk.isEntry) continue
        const kb = Buffer.byteLength(chunk.code) / 1000
        if (kb > FIRST_LOAD_BUDGET_KB) {
          this.error(
            `${chunk.fileName} is ${kb.toFixed(1)} kB, over the ${FIRST_LOAD_BUDGET_KB} kB first-load budget. ` +
              `Load the new code on demand (see tabModules in src/App.tsx), or raise the budget on purpose.`,
          )
        }
      }
    },
  }
}

/**
 * Installable, and able to open offline (#171).
 *
 * `prompt`, not `autoUpdate`: a new deploy waits until the reader agrees to
 * reload (`AppStatus`), because reloading under someone mid-trade loses it.
 *
 * What is cached, and how:
 * - **The app** (code, styles, fonts, icons) is precached, so it always opens.
 * - **`/data`** is cached as it is fetched and refreshed in the background. It
 *   is not precached: the sample league and the value snapshots alone are over
 *   2 MB, and most visitors never open either.
 * - **Sleeper, FantasyCalc and DynastyProcess** are network-first with the last
 *   good answer as the fallback, so offline the last-loaded league still opens.
 *   Sleeper's 5 MB player index is left out: the app already keeps it in
 *   IndexedDB (`lib/cache`), and a second copy would only cost space.
 *
 * The name, colours and icons below are the ones the home screen shows. The
 * icons are generated by `npm run icons` from the favicon's mark.
 */
const pwa = VitePWA({
  registerType: 'prompt',
  injectRegister: null,
  includeAssets: ['favicon.svg', 'apple-touch-icon.png'],
  manifest: {
    name: 'Dynasty Utility',
    short_name: 'Dynasty',
    description:
      'A dynasty fantasy football utility that knows your league: trade calculator, roster analysis, and trade suggestions.',
    // Relative, so both resolve against `base` on GitHub Pages.
    start_url: '.',
    scope: '.',
    display: 'standalone',
    // The dark page, which the app opens onto for most readers; the azure is
    // the action colour, used for the status bar where a browser tints it.
    background_color: '#0a0c10',
    theme_color: '#2563eb',
    icons: [
      { src: 'icon-192.png', sizes: '192x192', type: 'image/png' },
      { src: 'icon-512.png', sizes: '512x512', type: 'image/png' },
      { src: 'icon-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
    ],
  },
  workbox: {
    globPatterns: ['**/*.{js,css,html,svg,png,woff2}'],
    // `og.png` is for link previews, read by scrapers rather than readers.
    // The fonts' non-Latin subsets are fetched by `unicode-range` only when a
    // page uses those characters, which player names do not; precaching them
    // would add about 190 kB to every install for nothing.
    globIgnores: [
      'og.png',
      'data/**',
      '**/*-{latin-ext,cyrillic,cyrillic-ext,greek,greek-ext,vietnamese}-*.woff2',
    ],
    navigateFallback: 'index.html',
    cleanupOutdatedCaches: true,
    runtimeCaching: [
      {
        urlPattern: ({ url, sameOrigin }) => sameOrigin && url.pathname.includes('/data/'),
        handler: 'StaleWhileRevalidate',
        options: {
          cacheName: 'data',
          expiration: { maxEntries: 80 },
        },
      },
      {
        urlPattern: ({ url }) =>
          (url.hostname === 'api.sleeper.app' && !url.pathname.startsWith('/v1/players')) ||
          url.hostname === 'api.fantasycalc.com' ||
          url.hostname === 'raw.githubusercontent.com',
        handler: 'NetworkFirst',
        options: {
          cacheName: 'live',
          networkTimeoutSeconds: 10,
          expiration: { maxEntries: 400, maxAgeSeconds: 30 * 24 * 60 * 60 },
          cacheableResponse: { statuses: [200] },
        },
      },
    ],
  },
})

// https://vite.dev/config/
export default defineConfig({
  // Served from https://kfsalem.github.io/Dynasty-Trade-Calculator/
  base: '/Dynasty-Trade-Calculator/',
  plugins: [react(), tailwindcss(), firstLoadBudget(), pwa],
  test: {
    /**
     * Two suites, one command, split by extension: `.test.ts` is logic and runs
     * in node, `.test.tsx` mounts something and needs a DOM.
     *
     * The split is worth the config. The logic suite is several hundred tests
     * that finish in well under a second, and pushing all of them through jsdom
     * to serve the handful that need it would tax every future test to pay for
     * these.
     */
    projects: [
      {
        extends: true,
        test: {
          name: 'logic',
          environment: 'node',
          // `scripts/` too: the build-time ingest is tested and is not in src.
          include: ['src/**/*.test.ts', 'scripts/**/*.test.ts'],
        },
      },
      {
        extends: true,
        test: {
          name: 'dom',
          environment: 'jsdom',
          setupFiles: ['./src/test/setup.ts'],
          include: ['src/**/*.test.tsx'],
        },
      },
    ],
  },
})
